# seed.py
# A script to insert a test player into the database.

from database import SessionLocal, Player

# 1. Open a database session
db = SessionLocal()

# 2. Create a new player object
new_player = Player(nickname="Iniobong", xp=100)

# 3. Add the player to the database and save
db.add(new_player)
db.commit()
db.refresh(new_player) # This gets the new ID generated by the database

print(f"Player created! ID: {new_player.id}, Nickname: {new_player.nickname}, XP: {new_player.xp}")

# 4. Close the session
db.close()